addpath(packageRoot, fullfile(packageRoot, 'functions', 'foundation'), ...
    fullfile(packageRoot, 'functions', 'preparation'), ...
    fullfile(packageRoot, 'functions', 'gap_aware'), ...
    fullfile(packageRoot, 'functions', 'utilities'));

