    plot(S.time, S.xMm, '.', 'MarkerSize', 4, ...
        'DisplayName', sprintf('Probe %d', sensorIds(is)));
end
grid on; box on;
xlabel('Time (s)');
ylabel('Relative displacement (mm)');
title(sprintf('Low-speed self-check, blade slot %d should stay near 0', targetBladeSlot));
