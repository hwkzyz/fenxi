lowDir = fullfile(dataRoot, '900');
highDir = fullfile(dataRoot, '3000_3150');

sensorIds = [2 3 4 5 6 7];
bladeCount = 6;
sampleRateHz = 5e6;
rTipMm = 65.0;
thisDir = fileparts(mfilename('fullpath'));
packageCfg = Config_20241106();
if packageCfg.preparation.rebuildFromRaw
    Run_Script_Isolated_20241106(fullfile(packageCfg.paths.preparation, ...
        'Step01_Build_LowSpeed_Reference_20241106.m'));
    Run_Script_Isolated_20241106(fullfile(packageCfg.paths.preparation, ...
        'Step02_Extract_Dynamic_BTT_20241106.m'));
    Run_Script_Isolated_20241106(fullfile(packageCfg.paths.foundation, ...
        'Step03_Build_Dynamic_Observation_Bundle_20241106.m'));
    Run_Script_Isolated_20241106(fullfile(packageCfg.paths.preparation, ...
        'Step04_Build_LowSpeed_OPRCenterStd_Template_20241106.m'));
else
    Prepare_Bundled_Inputs_20241106(packageCfg);
end
dataRoot = packageCfg.paths.rawDatasetRoot;
lowDir = fullfile(dataRoot, '900');
highDir = fullfile(dataRoot, '3000_3150');
outDir = packageCfg.paths.gapRuntime;
if ~exist(outDir, 'dir')
    mkdir(outDir);
