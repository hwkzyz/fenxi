function C = R5_Check_Simulation_Experiment_DynamicContract()
%R5_CHECK_SIMULATION_EXPERIMENT_DYNAMICCONTRACT
% Check the current source contracts without reading historical result files.
% R4 has one synthetic common gap; R5 estimates one experimental dg_s per
% sensor.  That dimensional difference is intentional, not a hidden tilt.
thisDir = fileparts(mfilename('fullpath'));
r4File = fullfile(thisDir,'..','..','..','main_inv_log_2_method', ...
    '最新程序','r4_pc1_manifold_transfer','Main_04_TransferredSurfaceDynamicValidation.m');
r5File = fullfile(thisDir,'Main06_GapAware_FullWave_Identification_20251222.m');
assert(exist(r4File,'file') == 2 && exist(r5File,'file') == 2, ...
    'R5:ContractSource','Current R4 or R5 source program is missing.');
r4 = fileread(r4File); r5 = fileread(r5File);
checks = struct();
checks.r4_pc1_anchor_surface = contains(r4,'make_transferred_library') && ...
    contains(r4,'build_path_template_model');
checks.r5_pc1_anchor_surface = contains(r5,'R5_PC1_AnchorSurface_SensorWiseDg_FullWave') && ...
    contains(r5,'target_excluded_PC1_family_B2_registration_low_speed_anchor');
checks.r4_dynamic_clearance = contains(r4,'eval_gap_template(model,z(1)');
checks.r5_sensorwise_dynamic_clearance = contains(r5,'sensor_wise_dynamic_gap') && ...
    contains(r5,'deltaGapMm');
checks.r5_legacy_tilt_disabled_in_main = contains(r5,'Formal R5 production forbids the legacy');
assert(all(structfun(@(x) logical(x),checks)), ...
    'R5:ContractMismatch','The current R4/R5 source contracts are not aligned.');
C = struct('status','PASS','checks',checks, ...
    'shared_principle','fixed PC1/anchor static surface plus high-speed clearance-aware waveform fitting', ...
    'r4_clearance_parameterization','one common synthetic g because the R4 map is controlled and common-gap', ...
    'r5_clearance_parameterization','independent experimental dg_s,w for each active sensor and window', ...
    'pc1_dynamic_state',false,'delta_mu_enabled',false,'delta_tau_enabled',false, ...
    'notes','This verifies conceptual/source alignment only; it does not compare historical numerical results.');
disp(C);
end
