% v14 - replace the legacy C1/C2 panel with the transferred-surface
% dynamic validation; keep the visible MATLAB figure open for review.
% a : calibration/rotor relative-geometry schematic
% b : complete FE waveform family
% c : geometry-induced response difference
% d : blind cross-gap transfer NRMSE
% e : representative blind-transfer waveforms
% f : downstream dynamic residual after surface transfer

root = fileparts(mfilename('fullpath'));

r4 = fullfile( ...
    fileparts(fileparts(root)), ...
    'r4_pc1_manifold_transfer', ...
    'output');

od = root;

if ~exist(od,'dir')
    mkdir(od);
end

raw = load(fullfile( ...
    r4, ...
