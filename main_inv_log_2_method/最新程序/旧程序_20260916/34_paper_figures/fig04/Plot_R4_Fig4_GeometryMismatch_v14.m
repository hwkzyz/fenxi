% =========================================================================

function S = drawSensorA( ...
    ax,cx,mountY,tiltDeg,shapeScale, ...
    blue,darkGrey,midGrey,lightGrey)

%% Casing

halfW = 0.120 * shapeScale;

xc = linspace( ...
    cx-halfW, ...
    cx+halfW, ...
    150);

yc = ...
    mountY ...
    - (0.006*shapeScale)* ...
    ((xc-cx)/halfW).^2;

plot(ax,xc,yc, ...
    'Color',midGrey, ...
    'LineWidth',0.65);

%% Sensor rotation

th = ...
    tiltDeg*pi/180;

R = [ ...
    cos(th) -sin(th)
    sin(th)  cos(th)];

pivot = [ ...
    cx
    mountY];

%% Housing

housingW = ...
    0.067*shapeScale;

P = [ ...
    -housingW/2 ...
     housingW/2 ...
     housingW/2 ...
    -housingW/2
     0.003*shapeScale ...
     0.003*shapeScale ...
     0.039*shapeScale ...
     0.039*shapeScale];

P = R*P;

P(1,:) = ...
    P(1,:) + pivot(1);

P(2,:) = ...
    P(2,:) + pivot(2);

patch(ax, ...
    P(1,:),P(2,:), ...
    lightGrey, ...
    'EdgeColor',darkGrey, ...
    'LineWidth',0.55);

%% Probe

probeW = ...
    0.018*shapeScale;

Q = [ ...
    -probeW/2 ...
     probeW/2 ...
     probeW/2 ...
    -probeW/2
    -0.014*shapeScale ...
    -0.014*shapeScale ...
     0.008*shapeScale ...
     0.008*shapeScale];

Q = R*Q;

Q(1,:) = ...
    Q(1,:) + pivot(1);

Q(2,:) = ...
    Q(2,:) + pivot(2);

patch(ax, ...
    Q(1,:),Q(2,:), ...
    blue, ...
    'EdgeColor','none');

%% Sensing face

F = [ ...
    -probeW*0.65 ...
     probeW*0.65
    -0.014*shapeScale ...
    -0.014*shapeScale];

F = R*F;

F(1,:) = ...
    F(1,:) + pivot(1);

F(2,:) = ...
    F(2,:) + pivot(2);

plot(ax, ...
    F(1,:),F(2,:), ...
    'Color',blue, ...
    'LineWidth',0.92);

faceCentre = ...
    mean(F,2);

senseDir = ...
    R*[0;-1];

