    'Parent',f, ...
    'Position',[ ...
    pL+3*(pW+pGX), ...
    pB-(pH+pGY), ...
    pW, ...
    pH]);

axis(axBL,[0 1 0 1]);
axis(axBL,'off');
hold(axBL,'on');

text(axBL, ...
    0.50,0.91, ...
    'g (mm)', ...
    'HorizontalAlignment','center', ...
    'FontWeight','bold', ...
    'FontSize',6.3);

for j = 1:nG

    cc = 1 + (j>3);
    rr = j - 3*(cc-1);

    x0 = 0.06 + 0.50*(cc-1);
    y0 = 0.66 - 0.25*(rr-1);

    plot(axBL, ...
        [x0 x0+0.18], ...
        [y0 y0], ...
        'Color',gapCols(j,:), ...
        'LineWidth',1.35);

    text(axBL, ...
        x0+0.23, ...
        y0, ...
        sprintf('%.2f',g(j)), ...
        'FontSize',5.9, ...
        'VerticalAlignment','middle');

end

%% ========================================================================
% Lower row
% =========================================================================

