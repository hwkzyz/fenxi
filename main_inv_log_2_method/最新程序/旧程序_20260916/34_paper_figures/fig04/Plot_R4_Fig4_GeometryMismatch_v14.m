if isempty(validE)
    mxE = 1;
else
    mxE = max(validE);
end

for is = 1:nS

    for ig = 1:nG

        if isnan(E(is,ig))
            continue;
        end

        if E(is,ig) > 0.72*mxE
            tc = 'w';
        else
            tc = dark;
        end

        text(axD, ...
            g(ig), ...
            states(is), ...
            sprintf('%.2f',E(is,ig)), ...
            'HorizontalAlignment','center', ...
            'FontSize',4.9, ...
            'Color',tc);

    end

end

%% ========================================================================
% e
% =========================================================================

addPanelLetter( ...
    f,'e', ...
    0.535,panelLetterY);

eTopPos = [ ...
    0.565 ...
    0.295 ...
    0.165 ...
    0.145];

eBotPos = [ ...
    0.565 ...
    0.105 ...
    0.165 ...
    0.145];

ePos = { ...
    eTopPos, ...
    eBotPos};

anchorIndex = ...
    find(abs(g-1.10)<1e-12,1);

for ic = 1:2

    if ic == 1
        it = 1;
    else
        it = nS;
    end

    pred = blindPrediction( ...
        V,g,it,anchorIndex);

    axE = axes( ...
        'Parent',f, ...
        'Position',ePos{ic});

