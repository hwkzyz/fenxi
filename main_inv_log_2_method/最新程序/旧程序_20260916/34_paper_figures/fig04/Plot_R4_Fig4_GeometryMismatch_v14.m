%% ========================================================================
% Complete rig
% =========================================================================

function G = drawRigA( ...
    ax,cx,mountY, ...
    sensorTiltDeg,centreShiftX, ...
    bladeScale,gapLength,shapeScale, ...
    showGap,showMismatch, ...
    blue,orange,darkGrey,midGrey,lightGrey, ...
    diskFill,targetFill,targetEdge, ...
    neighFill,neighEdge,refGrey)

Rtip = 1.95;

RtipPlot = Rtip*bladeScale;

S = drawSensorA( ...
    ax,cx,mountY,sensorTiltDeg,shapeScale, ...
    blue,darkGrey,midGrey,lightGrey);

tip = ...
    S.faceCentre + ...
    gapLength*S.senseDir;

centreRef = ...
    tip + ...
    RtipPlot*S.senseDir;

centreX = ...
    centreRef(1) + ...
    centreShiftX;

dx = ...
    centreX-tip(1);

if abs(dx) >= RtipPlot

    error( ...
        'Panel-a centre shift exceeds rotor radius.');

end

dy = ...
    sqrt(RtipPlot^2-dx^2);

centre = [ ...
    centreX
    tip(2)-dy];

outwardRadial = ...
    (tip-centre)/RtipPlot;

inwardRadial = ...
    -outwardRadial;

betaTarget = ...
    atan2d( ...
    outwardRadial(2), ...
    outwardRadial(1));

drawRotorAssemblyA( ...
    ax,centre,betaTarget,bladeScale, ...
    diskFill,targetFill,targetEdge, ...
    neighFill,neighEdge,midGrey);

%% Rotor centre marker: graphical element, enlarged

plot(ax, ...
    centre(1),centre(2), ...
    '.', ...
    'Color',darkGrey, ...
    'MarkerSize',6*shapeScale);

%% Clearance g
if showGap

    % -------------------------------------------------------------
    % Physical endpoints:
    % upper = sensor sensing face
    % lower = measured blade tip
    % -------------------------------------------------------------

    yTop = S.faceCentre(2);
    yBot = tip(2);

    % Keep the dimension arrow inside the actual sensor-tip gap.
    % Only a small lateral offset is used to avoid covering
    % the central sensing axis / blade.
    xGap = S.faceCentre(1) - 0.030;

    % Small inward padding so arrowheads do not visually touch
    % the sensor face / blade-tip contour.
    pad = 0.0035;

    y1 = yTop - pad;
    y2 = yBot + pad;


    %% ------------------------------------------------------------
    % Short witness / extension lines
    % These explicitly connect the dimension to the physical
    % sensor face and blade tip.
    % -------------------------------------------------------------

    guideCol = [0.55 0.55 0.55];

    % sensor-face guide
    plot(ax, ...
        [xGap+0.004 S.faceCentre(1)-0.004], ...
        [yTop yTop], ...
        '-', ...
        'Color',guideCol, ...
        'LineWidth',0.45);

    % blade-tip guide
    plot(ax, ...
        [xGap+0.004 tip(1)-0.004], ...
        [yBot yBot], ...
        '-', ...
        'Color',guideCol, ...
        'LineWidth',0.45);


    %% ------------------------------------------------------------
    % Double arrow
    % -------------------------------------------------------------

    drawDoubleArrowA( ...
        ax,xGap,y1,y2,darkGrey, ...
        0.0048*shapeScale, ...
        0.0038*shapeScale, ...
        0.55);


    %% ------------------------------------------------------------
    % g label
    %
    % Only move the TEXT to the left.
    % Do not move the physical dimension itself.
    % -------------------------------------------------------------

    text(ax, ...
        xGap-0.018, ...
        (yTop+yBot)/2, ...
        'g', ...
        'FontSize',5.8, ...
