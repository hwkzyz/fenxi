%% ========================================================================
% Blind transfer prediction
% =========================================================================

function pred = blindPrediction( ...
    V,g,targetIndex,anchorIndex)

[nX,nG,nS] = ...
    size(V);

gref = 0.8;

X = [ ...
    ones(nG,1), ...
    1./g, ...
    log(g/gref)];

train = ...
    setdiff(1:nS,targetIndex);

Q = zeros( ...
    3*nX, ...
    numel(train));

for k = 1:numel(train)

    B = ...
        (X\V(:,:,train(k)).').';

    Q(:,k) = ...
        B(:);

end

mu = ...
    mean(Q,2);

[U,~,~] = ...
    svd(Q-mu,'econ');

Ur = ...
    U(:,1:min(2,size(U,2)));

Z = ...
    Ur'*(Q-mu);

[z1,ord] = ...
    sort(Z(1,:),'ascend');

Qord = ...
    Q(:,ord);

dz = ...
    max(diff(z1));

tgrid = ...
    linspace( ...
    z1(1)-0.5*dz, ...
    z1(end)+0.5*dz, ...
    401);

y = ...
    V(:,anchorIndex,targetIndex);

dist = ...
    nan(size(tgrid));

for k = 1:numel(tgrid)

    q = interp1( ...
        z1, ...
        Qord.', ...
        tgrid(k), ...
        'linear', ...
        'extrap').';

    B = ...
        reshape(q,nX,3);

    dist(k) = ...
        sqrt(mean( ...
        (B*X(anchorIndex,:).' - y).^2));

end

[~,ix] = ...
    min(dist);

q = interp1( ...
    z1, ...
    Qord.', ...
    tgrid(ix), ...
    'linear', ...
    'extrap').';

pred = ...
    reshape(q,nX,3)*X.';

end


