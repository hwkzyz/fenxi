    'FontSize',7, ...
    'Color',dark, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle');

axEL = axes( ...
    'Parent',f, ...
    'Position',[ ...
    0.565 ...
    0.455 ...
    0.165 ...
    0.025]);

axis(axEL,[0 1 0 1]);
axis(axEL,'off');
hold(axEL,'on');

