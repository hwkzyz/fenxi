headerH = 0.012;

%% ========================================================================
% c
% =========================================================================

cPos = [ ...
    0.050 ...
    0.105 ...
    0.195 ...
    0.335];

axC = axes( ...
    'Parent',f, ...
    'Position',cPos);

hold(axC,'on');

