    f,'c', ...
    0.028,panelLetterY);

delta = squeeze( ...
    V(:,:,end)-V(:,:,1));

imagesc(axC,x,g,delta');

axis(axC,'xy');

ylim(axC,[min(g) max(g)]);

lim = max(abs(delta(:)));

clim(axC,[-lim lim]);

colormap(axC,blueWhiteRed(256));

set(axC, ...
    'YTick',g, ...
    'FontSize',6.25, ...
    'TickDir','out', ...
    'Box','off');

