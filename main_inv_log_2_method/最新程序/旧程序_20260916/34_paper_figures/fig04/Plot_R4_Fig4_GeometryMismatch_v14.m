%% ========================================================================
% Original curved blade geometry
% =========================================================================

function [xb,yb,tipAngle] = ...
    originalImpellerBladeA()

Rhub = 1.00;
Rtip = 1.95;

theta0 = ...
    5*pi/180;

sweep = ...
    38*pi/180;

wRoot = ...
    2.5*pi/180;

wMax = ...
    5.0*pi/180;

t = ...
    linspace(0,1,220);

r = ...
    Rhub + ...
    (Rtip-Rhub).*t;

theta_c = ...
    theta0 + ...
    sweep.*t.^1.15;

width = ...
    wRoot.*(1-t) + ...
    wMax.*sin(pi*t).^0.9;

theta1 = ...
    theta_c + width;

theta2 = ...
    theta_c - width;

x1 = ...
    r.*cos(theta1);

y1 = ...
    r.*sin(theta1);

x2 = ...
    r.*cos(theta2);

y2 = ...
    r.*sin(theta2);

xb = [ ...
    x1 ...
    fliplr(x2)];

yb = [ ...
    y1 ...
    fliplr(y2)];

tipAngle = ...
    theta0+sweep;

end


