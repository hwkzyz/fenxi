    py = pB - (row-1)*(pH+pGY);

    ax = axes( ...
        'Parent',f, ...
        'Position',[px py pW pH]);

    hold(ax,'on');

    for j = 1:nG

        plot(ax, ...
            x, ...
            V(:,j,k), ...
            'Color',gapCols(j,:), ...
            'LineWidth',0.82);

    end

    xlim(ax,[min(x) max(x)]);

    ylim(ax,[ ...
        vLim(1) ...
        vLim(2)+0.045]);

    set(ax, ...
        'FontSize',5.6, ...
        'LineWidth',0.50, ...
        'TickDir','out', ...
        'Box','off', ...
        'XTick',[-5 0 5], ...
        'YTick',[0.15 0.25 0.35]);

    stateLabel = [ ...
        num2str(states(k),'%.1f') ...
        char(176)];

    title(ax, ...
        stateLabel, ...
        'FontSize',6.3, ...
        'FontWeight','normal');

    if row == 2

        xlabel(ax, ...
            '\it x\rm (mm)', ...
            'FontSize',6.5);

    else

        ax.XTickLabel = [];

    end

