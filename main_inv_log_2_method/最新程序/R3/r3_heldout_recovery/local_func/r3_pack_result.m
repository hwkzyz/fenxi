function row = r3_pack_result(fit,truth,P,thresholdMm,C0)
%R3_PACK_RESULT Convert one fit into a traceable replicate-level row.

Ahat=fit.A_id;phaseError=NaN;ampTol=NaN;vibSuccess=false;falsePositive=NaN;
if truth.A_true_mm>0
    ampTol=max(P.amplitudeAbsToleranceMm,P.amplitudeRelTolerance*truth.A_truth_mapped_mm);
    phaseError=abs(atan2(sin(fit.phi_id-truth.phi_mapped_rad),...
        cos(fit.phi_id-truth.phi_mapped_rad)));
    vibSuccess=fit.eo_id==truth.eo_true&&...
        abs(Ahat-truth.A_truth_mapped_mm)<=ampTol&&phaseError<=P.phaseToleranceRad;
elseif isfinite(thresholdMm)
    falsePositive=Ahat>thresholdMm;
end
gModel=fit.g_used;
deltaGapEst=gModel-C0.pathCal.g0;
gapError=gModel-truth.g_truth_mm;
jointSuccess=truth.A_true_mm>0&&vibSuccess&&abs(gapError)<=P.gapToleranceMm;
si=fit.fit.solve_info;
row=struct('method',string(fit.r3_method),'g_reference_mm',truth.g_reference_mm,...
    'g_low_model_mm',C0.pathCal.g0,'g_truth_mm',truth.g_truth_mm,...
    'delta_gap_truth_mm',truth.delta_gap_truth_mm,'A_true_mm',truth.A_true_mm,...
    'A_truth_mapped_mm',truth.A_truth_mapped_mm,'eo_true',truth.eo_true,...
    'f_true_hz',truth.f_true_hz,'phi_injected_rad',truth.phi_injected_rad,...
    'phi_mapped_rad',truth.phi_mapped_rad,...
    'phase_mapping_residual_rms_mm',truth.phase_mapping_residual_rms_mm,...
    'noise_std_V',truth.noise_std_V,'low_seed',C0.r3_low_seed,...
    'high_seed',truth.high_seed,'g_model_coordinate_mm',gModel,...
    'delta_gap_est_from_calibration_mm',deltaGapEst,'g_est_mm',gModel,...
    'gap_error_mm',gapError,'A_est_mm',Ahat,...
    'amplitude_error_mm',Ahat-truth.A_truth_mapped_mm,'amplitude_tolerance_mm',ampTol,...
    'eo_est',fit.eo_id,'f_est_hz',fit.f_id,'phi_est_rad',fit.phi_id,...
    'phase_error_rad',phaseError,'rmse_V',fit.rmse,'vib_success',vibSuccess,...
    'detection_threshold_mm',thresholdMm,'false_positive',falsePositive,...
    'joint_success',jointSuccess,'solver',string(si.solver),'exitflag',si.exitflag,...
    'iterations',si.iterations,'function_count',si.funcCount,...
    'elapsed_s',fit.elapsed_r3_s,'candidate_count',fit.candidate_count,...
    'used_sample_count',fit.used_sample_count);
end
